-- VA-43: subcategorías Pistón / Turbohélice en Monomotor y Bimotor (migración de datos).
-- Mantiene los ids existentes; no cambia el schema. Decisiones D3, D12 y D15 (docs/PLAN_FIXES_MVP.md).

-- 1. Categorías: MP/BP pasan a "Pistón", se crean MT/BT y S/C pasa a "Otros".
UPDATE "AircraftCategory" SET "name" = 'Monomotor Pistón' WHERE "id" = 'MP';
UPDATE "AircraftCategory" SET "name" = 'Bimotor Pistón' WHERE "id" = 'BP';
UPDATE "AircraftCategory" SET "name" = 'Otros' WHERE "id" = 'S/C';
INSERT INTO "AircraftCategory" ("id", "name") VALUES
  ('MT', 'Monomotor Turbohélice'),
  ('BT', 'Bimotor Turbohélice')
ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name";

-- 2. Avisos que cambian de categoría (D3): solo el Pilatus PC-12, que es monomotor turbohélice.
UPDATE "Aircraft" a
SET "categoryId" = 'MT'
FROM "AircraftModel" m
JOIN "AircraftBrand" b ON b."id" = m."brandId"
WHERE a."modelId" = m."id" AND b."name" = 'PILATUS' AND m."name" = 'PC-12' AND a."categoryId" = 'BP';

-- 3. engineType sale de la categoría (VA-21): Pistón en MP/BP, Turbohélice en MT/BT.
--    En el resto de las categorías no se toca lo que ya hubiera.
UPDATE "Aircraft" SET "engineType" = 'PISTON' WHERE "categoryId" IN ('MP', 'BP');
UPDATE "Aircraft" SET "engineType" = 'TURBOPROP' WHERE "categoryId" IN ('MT', 'BT');

